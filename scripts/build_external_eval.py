def _two_member_readout(scored: pd.DataFrame, group: str, condition: str) -> dict:
    """Per-attribute AR and IR beside the set-level discordant share, for 2-member sets.

    The record of the scorer finding: under `attribute_biased`, IR is 1.0 for the hired
    attribute and 0.0 for the rejected one, which is the acceptance gap again.
    """
    chunk = scored[(scored["protected_group"] == group) & (scored["condition"] == condition)]
    decided = chunk[chunk["outcome"] == "decided"]
    per_set = decided.groupby("group_id")["decision"].agg(["size", "nunique"])
    full = per_set[per_set["size"] == 2]
    by_attr = decided.groupby("protected_attr")
    return {
        "per_attribute": {
            attr: {"acceptance_rate": float((rows["decision"] == "hire").mean()),
                   "inconsistency_rate": float(rows["inconsistent"].mean())}
            for attr, rows in by_attr},
        "group_inconsistency_rate": float(decided["inconsistent"].mean()),
        "discordant_set_share": float((full["nunique"] == 2).mean()) if len(full) else None,
        "n_sets_both_decided": len(full),
    }


def scorer_check(frame: pd.DataFrame, name: str, n_permutations: int, audit_cfg: dict) -> dict:
    """score_run on fabricated outputs; records what is defined, what is not, what raises.

    Also runs `select_for_audit` with the audit config the frames were sized for, which is
    what the proposed runner hook would hand to the generator: it shows each frame keeps its
    own sets rather than being cut to its attr_free rows by the config's benchmark groups.
    """
    from hiring_bias_mitigation.analysis import stability as ST
    from hiring_bias_mitigation.eval import audit as A
    from hiring_bias_mitigation.eval.parsing import parse_frame

    results: dict = {}
    try:
        _, covered = X.select_for_audit(frame, audit_cfg)
        results["hook_selection"] = {"ok": True, **covered}
    except ValueError as exc:
        results["hook_selection"] = {"ok": False, "error": str(exc)}
    for mode in ("constant_hire", "random", "attribute_biased"):
        parsed = parse_frame(frame.assign(raw_output=X.fabricate_raw_outputs(frame, mode)))
        entry: dict = {"n_rows": len(parsed),
                       "outcomes": dict(Counter(parsed["outcome"]))}
        started = time.time()
        try:
            record = A.score_run(parsed, f"fabricated--{name}--{mode}",
                                 {"frame": name, "fabricated": mode},
                                 similarity=None, n_permutations=n_permutations)
            scored, summary = record.scored, record.summary
            entry.update({
                "ok": True,
                "seconds": round(time.time() - started, 1),
                "summary": {k: summary.get(k) for k in (
                    "n_total", "n_decided", "parse_failure_rate", "population_acceptance_rate",
                    "attr_free_acceptance_rate", "reference_agreement",
                    "attr_free_reference_agreement", "attribute_mention_rate",
                    "mean_feedback_similarity", "n_tests", "usable")},
                "disparity_conditions": sorted(summary["disparity"]["by_condition"]),
                "group_keys": list(record.groups),
                "groups": {
                    key: {
                        "n_attributes": g["n_attributes"],
                        "reference_attr": g["effect_sizes"].get("reference_attr"),
                        "inconsistency_rate": g["population"]["inconsistency_rate"],
                        "reference_agreement": g["population"]["reference_agreement"],
                        "paired_p_defined": int(pd.Series(
                            [r.get("acceptance_rate__paired_p") for r in g["attributes"]],
                            dtype=float).notna().sum()),
                    } for key, g in record.groups.items()},
                "reference_bucket": dict(Counter(scored["reference_bucket"].astype(str))),
                "agrees_with_reference": dict(Counter(
                    scored["agrees_with_reference"].map(lambda v: "nan" if v != v else str(v)))),
                "acceptance_rate__ref_hire_defined": any(
                    pd.notna(r.get("acceptance_rate__ref_hire"))
                    for g in record.groups.values() for r in g["attributes"]),
                "manual_review_checks": sorted({i["check"] for i in record.manual_review}),
                "two_member_groups": {
                    key: _two_member_readout(scored, g["protected_group"], g["condition"])
                    for key, g in record.groups.items() if g["n_attributes"] == 2},
            })
        except Exception as exc:  # noqa: BLE001 -- the failure is the result being recorded
            entry.update({"ok": False, "error": f"{type(exc).__name__}: {exc}",
                          "traceback_tail": traceback.format_exc().splitlines()[-6:]})
        # analysis/stability.py keys a set by (pair_id, condition), not by group_id, and drops
        # attr_free; this is how that tool would see the frame.
        rows = parsed[parsed["condition"] != "attr_free"].assign(
            d=parsed["decision"].where(parsed["decision"].isin(["hire", "reject"])))
        if len(rows):
            table = ST.set_table(rows)
            entry["stability_tool_sets"] = {
                "n_sets": len(table),
                "variants_per_set": {str(k): v for k, v in
                                     sorted(Counter(table["variants"]).items())},
                "unstable_share": float(table["unstable"].mean()),
            }
        else:
            entry["stability_tool_sets"] = {"n_sets": 0,
                                            "note": "every row is attr_free; the tool drops them"}
        results[mode] = entry
    return results


def calibrate_tokens(frames: dict, tokenizer_name: str, budget: X.LengthBudget,
                     per_frame: int = 100) -> dict:
    """Exact prompt tokens (chat template applied) against the estimate, offline.

    The `per_frame` longest rows by estimate plus as many evenly spaced ones: the long tail is
    where the over-length flag matters, the spread shows the ratio elsewhere.
    """
    from transformers import AutoTokenizer

    tok = AutoTokenizer.from_pretrained(tokenizer_name)
    out = {"tokenizer": tokenizer_name}
    for name, (frame, _, _) in frames.items():
        longest = frame.nlargest(per_frame, "est_prompt_tokens").index
        spread = frame.index[:: max(1, len(frame) // per_frame)]
        rows = frame.loc[sorted(set(longest) | set(spread))]
        exact = []
        for row in rows.to_dict("records"):
            text = tok.apply_chat_template([{"role": "user", "content": P.build_prompt(row)}],
                                           tokenize=False, add_generation_prompt=True,
                                           enable_thinking=False)
            exact.append(len(tok(text)["input_ids"]))
        exact = pd.Series(exact, index=rows.index)
        ratio = rows["est_prompt_tokens"] / exact
        out[name] = {
            "n_rows_tokenized": len(rows),
            "estimate_over_exact": {"min": float(ratio.min()), "p50": float(ratio.median())},
            "n_estimate_below_exact": int((ratio < 1).sum()),
            "max_exact_tokens": int(exact.max()),
            "n_over_by_estimate": int(rows["over_max_model_len"].sum()),
            "n_over_by_exact": int(exact.map(budget.over).sum()),
        }
    return out


def write_samples(frames: dict, path: Path) -> None:
    lines = ["Rendered prompts, 3 per frame (data/prompts.build_prompt, baseline strategy).",
             "Two members of the first counterfactual set, then the attr_free row of the same",
             "pair (or a third member where the frame has none).", ""]
    for name, (frame, _, _) in frames.items():
        for row in X.sample_rows(frame).to_dict("records"):
            lines += ["=" * 100,
                      f"frame={name} | group_id={row['group_id']} | "
                      f"protected_attr={row['protected_attr']} | condition={row['condition']} | "
                      f"variant_cv_id={row['variant_cv_id']}",
                      "-" * 100, P.build_prompt(row), ""]
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--frames", nargs="+", default=FRAMES, choices=FRAMES)
    parser.add_argument("--external-root", default=None,
                        help="staged sources (default $HBM_EXTERNAL_ROOT or "
                             "$HBM_OUTPUT_ROOT/external_data)")
    parser.add_argument("--out-dir", default=None,
                        help="output directory (default $HBM_OUTPUT_ROOT/external_eval)")
    parser.add_argument("--audit-config", default=str(DEFAULT_AUDIT_CONFIG),
                        help="audit config whose max_model_len, max_new_tokens and "
                             "max_intersection_cells the frames are sized for")
    parser.add_argument("--eval-scope", default=str(DEFAULT_EVAL_SCOPE),
                        help="the groups/conditions file the injected frames follow")
    parser.add_argument("--no-scorer-check", action="store_true")
    parser.add_argument("--permutations", type=int, default=200,
                        help="permutations per test in the scorer check (outputs are fabricated, "
                             "so only whether the fields are defined matters)")
    parser.add_argument("--tokenizer", default=None,
                        help="a locally cached tokenizer to calibrate the token estimate against")
    args = parser.parse_args()

    root = Path(args.external_root) if args.external_root else external_root()
    if not root.is_dir():
        raise SystemExit(f"{root} does not exist; stage the external sources first.")
    out_dir = Path(args.out_dir) if args.out_dir else output_root() / "external_eval"
    out_dir.mkdir(parents=True, exist_ok=True)

    audit_cfg = load_yaml(args.audit_config)
    budget = X.LengthBudget.from_audit_config(audit_cfg)
    scope = X.english_scope(load_yaml(args.eval_scope))
    max_cells = audit_cfg.get("max_intersection_cells")
    config = {
        "audit_config": _repo_relative(args.audit_config),
        "max_model_len": budget.max_model_len, "max_new_tokens": budget.max_new_tokens,
        "chars_per_token": X.CHARS_PER_TOKEN, "chat_template_tokens": X.CHAT_TEMPLATE_TOKENS,
        "eval_scope": _repo_relative(args.eval_scope), "injected_groups": scope["groups"],
        "injected_conditions": scope["conditions"], "scope_by_model": scope["by_model"],
        "max_intersection_cells": max_cells, "external_root": str(root),
    }
    code = _code_version()

    frames = build(args.frames, root, budget, scope, max_cells)
    index = {}
    for name, (frame, exclusions, inputs) in frames.items():
        structure = X.assert_frame_structure(frame, name)
        parquet = out_dir / f"{name}.parquet"
        frame.to_parquet(parquet, index=False)
        stats = {
            "frame": name, "source": str(frame["source"].iloc[0]), "note": NOTES[name],
            "built_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"), "code": code,
            "inputs": inputs, "config": config,
            "reference": "none: reference_decision and reference_feedback are empty",
            "stats": X.frame_stats(frame), "exclusions": exclusions,
            "structure_check": structure, "columns": list(frame.columns),
        }
        (out_dir / f"{name}.stats.json").write_text(
            json.dumps(stats, indent=2, ensure_ascii=False, default=str), encoding="utf-8")
        index[name] = {"parquet": parquet.name, "rows": len(frame),
                       "sets": stats["stats"]["n_sets"], "pairs": stats["stats"]["n_pairs"]}
        log.info("%s: %d rows, %d sets -> %s", name, len(frame), stats["stats"]["n_sets"], parquet)

    write_samples(frames, out_dir / "prompt_samples.txt")

    if not args.no_scorer_check:
        check = {"permutations": args.permutations,
                 "audit_config": config["audit_config"],
                 "frames": {name: scorer_check(frame, name, args.permutations, audit_cfg)
                            for name, (frame, _, _) in frames.items()}}
        (out_dir / "scorer_check.json").write_text(
            json.dumps(check, indent=2, ensure_ascii=False, default=str), encoding="utf-8")
        for name, entry in check["frames"].items():
            log.info("hook selection %s: %s", name, entry["hook_selection"])
            for mode, result in entry.items():
                if mode == "hook_selection":
                    continue
                s = result.get("summary", {})
                log.info("scorer %s/%s: ok=%s ref_agreement=%s usable=%s %s", name, mode,
                         result.get("ok"), s.get("reference_agreement"), s.get("usable"),
                         result.get("error", ""))

    if args.tokenizer:
        calibration = calibrate_tokens(frames, args.tokenizer, budget)
        (out_dir / "token_calibration.json").write_text(json.dumps(calibration, indent=2),
                                                        encoding="utf-8")

    (out_dir / "index.json").write_text(json.dumps(index, indent=2), encoding="utf-8")
    print(json.dumps(index, indent=2))


if __name__ == "__main__":
    main()
