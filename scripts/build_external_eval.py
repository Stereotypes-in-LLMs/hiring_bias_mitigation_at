def _code_version() -> dict:
    def git(*args):
        try:
            return subprocess.run(["git", *args], cwd=REPO_ROOT, capture_output=True, text=True,
                                  timeout=30).stdout.strip()
        except (OSError, subprocess.SubprocessError):
            return ""
    return {"commit": git("rev-parse", "--short", "HEAD"),
            "uncommitted": [line for line in git("status", "--porcelain").splitlines() if line]}


def _repo_relative(path: str) -> str:
    resolved = Path(path).resolve()
    return str(resolved.relative_to(REPO_ROOT)) if resolved.is_relative_to(REPO_ROOT) else path


def build(names: list[str], root: Path, budget: X.LengthBudget, scope: dict,
          max_intersection_cells) -> dict[str, tuple[pd.DataFrame, dict, dict]]:
    """name -> (frame, exclusions, inputs)."""
    need = {
        X.SG: any(n.startswith("sg_") or n == "injected_sg" for n in names),
        X.FAIRE: any("faire" in n for n in names),
        X.TALENTCLEF: any("talentclef" in n for n in names),
        X.RJDB: "rjdb_qualification" in names,
    }
    data = {slug: X.load_source(slug, root) for slug, wanted in need.items() if wanted}
    sg, fa, tc, rj = (data.get(s) for s in (X.SG, X.FAIRE, X.TALENTCLEF, X.RJDB))
    out = {}

    def inputs(slug, tables):
        return X.input_files(slug, tables, root)

    for name in names:
        log.info("building %s", name)
        if name == "sg_native":
            frame = X.sg_native_frame(sg["cvs"], sg["jobs"], sg["pairs"], sg["variant_diffs"],
                                      sg["cue_inventory"], budget)
            out[name] = (frame, {}, inputs(X.SG, ["cvs", "jobs", "pairs", "variant_diffs",
                                                  "cue_inventory"]))
        elif name == "sg_language_only":
            frame, excl = X.sg_language_only_frame(sg["cvs"], sg["cvs_ablated"], sg["jobs"],
                                                   sg["pairs"], sg["cue_inventory"], budget)
            out[name] = (frame, excl, inputs(X.SG, ["cvs", "cvs_ablated", "jobs", "pairs",
                                                    "cue_inventory"]))
        elif name == "faire_names":
            frame, excl = X.faire_names_frame(fa["cvs"], fa["jobs"], fa["pairs"], budget)
            out[name] = (frame, excl, inputs(X.FAIRE, ["cvs", "jobs", "pairs"]))
        elif name == "talentclef_siblings":
            frame, excl = X.talentclef_sibling_frame(tc["cvs"], tc["jobs"], tc["pairs"],
                                                     budget=budget)
            out[name] = (frame, excl, inputs(X.TALENTCLEF, ["cvs", "jobs", "pairs"]))
        elif name == "rjdb_qualification":
            frame = X.rjdb_qualification_frame(rj["cvs"], rj["jobs"], rj["pairs"], budget=budget)
            out[name] = (frame, {}, inputs(X.RJDB, ["cvs", "jobs", "pairs"]))
        elif name.startswith("injected_"):
            slug, base = {
                "injected_sg": (X.SG, lambda: X.sg_base_pairs(sg["cvs"], sg["jobs"], sg["pairs"])),
                "injected_faire": (X.FAIRE, lambda: X.faire_base_pairs(fa["cvs"], fa["jobs"],
                                                                       fa["pairs"])),
                "injected_talentclef": (X.TALENTCLEF, lambda: X.talentclef_base_pairs(
                    tc["cvs"], tc["jobs"], tc["pairs"])),
            }[name]
            frame, excl = X.injected_frame(base(), name, slug, scope["groups"],
                                           scope["conditions"], max_intersection_cells, budget)
            excl.update(_upstream_exclusions(name, fa, tc, frame))
            out[name] = (frame, excl, inputs(slug, ["cvs", "jobs", "pairs"]))
        else:
            raise SystemExit(f"unknown frame {name!r}; expected one of {FRAMES}")
    return out


def _upstream_exclusions(name: str, faire: dict | None, talentclef: dict | None,
                         frame: pd.DataFrame) -> dict:
    """Bases the base-pair builders leave out before injection, so the stats count them."""
    if name == "injected_faire":
        _, dropped = X.faire_keep_bases(faire["cvs"])
        return {"duplicate_bases": {"n_pairs": len(dropped), "base_cv_ids": dropped}}
    if name == "injected_talentclef":
        cvs = talentclef["cvs"]
        designated = cvs[(cvs["lang"] == "en") & (cvs["split"] == "dev") & (cvs["variant"] == "")]
        paired = set(frame["candidate_id"])
        missing = sorted(c for c in designated["cv_id"]
                         if X.prefixed_id(X.TALENTCLEF, c) not in paired)
        return {"designated_bases_not_in_frame": {
            "n_bases": len(missing), "base_cv_ids": missing,
            "reason": "no positive JD in the dev qrels, or excluded above"}}
    return {}


