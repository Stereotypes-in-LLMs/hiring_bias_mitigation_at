"""Builds the external evaluation frames and checks the scorer can read them, without a model.

    python scripts/build_external_eval.py                       # every frame + scorer check
    python scripts/build_external_eval.py --frames faire_names sg_native
    python scripts/build_external_eval.py --tokenizer Qwen/Qwen3.5-9B   # also calibrate the
                                                                         # token estimate offline

Reads the staged sources under $HBM_EXTERNAL_ROOT (default $HBM_OUTPUT_ROOT/external_data) and
writes, under $HBM_OUTPUT_ROOT/external_eval:

    <frame>.parquet       build_eval_set's columns plus the frame's flag columns
    <frame>.stats.json    inputs (sha256), config, counts, every flag's count, exclusions, the
                          structure check, and what the frame does and does not measure
    prompt_samples.txt    three rendered prompts per frame (data/prompts.build_prompt)
    scorer_check.json     eval/audit.score_run on fabricated outputs for every frame
    index.json            one line per frame

Nothing is generated by a model and nothing reaches a runner: an audit config cannot point at
these frames yet. The scorer check fabricates decisions in the audit's JSON format (all hire,
a seeded coin flip, and a fixed attribute bias), parses them with eval/parsing.parse_frame and
scores them in-process, so that what works and what does not is a recorded result rather than
a guess. It also records what `external_eval.select_for_audit`, the selection a runner hook
would make, keeps of each frame under the audit config.
"""

